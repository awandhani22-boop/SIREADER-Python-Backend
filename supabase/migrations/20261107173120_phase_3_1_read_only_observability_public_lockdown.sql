CREATE VIEW public.v_api_system_runtime_state AS
SELECT execution_mode, trading_mode, auto_execution_enabled, auto_paused, updated_at
FROM public.runtime_control_state;
ALTER VIEW public.v_api_system_runtime_state OWNER TO sireader_view_owner;

CREATE VIEW public.v_api_telemetry_usage AS
SELECT
  usage_date, provider, model, tier, input_tokens, output_tokens,
  cache_read_tokens, cache_write_tokens, thinking_tokens, billing_currency,
  cost_rp, reserved_rp, cost_usd, reserved_usd, status, created_at, completed_at
FROM public.ai_usage_logs;
ALTER VIEW public.v_api_telemetry_usage OWNER TO sireader_view_owner;

CREATE VIEW public.v_api_active_in_flight_tasks AS
SELECT
  id AS task_id,
  status,
  created_at,
  GREATEST(
    0.0::double precision,
    EXTRACT(EPOCH FROM (statement_timestamp() - created_at))::double precision
  ) AS elapsed_seconds
FROM public.ai_analysis_logs
WHERE status = 'PROCESSING';
ALTER VIEW public.v_api_active_in_flight_tasks OWNER TO sireader_view_owner;

CREATE VIEW public.v_api_queued_pending_messages AS
SELECT
  id AS queue_item_id,
  status,
  CASE
    WHEN reason IN ('BLOCKED_HARD_BUDGET', 'MANUAL_REVIEW_BUDGET') THEN reason
    ELSE 'OTHER'
  END::varchar(40) AS queue_reason,
  attempts,
  claimed_at,
  created_at,
  updated_at
FROM public.ai_pending_messages
WHERE status IN ('PENDING', 'CLAIMED');
ALTER VIEW public.v_api_queued_pending_messages OWNER TO sireader_view_owner;

CREATE VIEW public.v_api_active_market_watches AS
SELECT
  id AS watch_id, symbol, status, spread_pips, maximum_spread_pips,
  last_bid, last_ask, check_count, last_checked_at, next_check_at, created_at, updated_at
FROM public.trade_decision_watches
WHERE status IN ('WAITING_FOR_SPREAD', 'RECHECKING');
ALTER VIEW public.v_api_active_market_watches OWNER TO sireader_view_owner;

CREATE VIEW public.v_api_audit_decisions AS
SELECT
  id AS audit_id,
  decision,
  previous_status,
  new_status,
  'Authorized Approver'::varchar(50) AS reviewer_role,
  created_at AS decided_at
FROM public.approval_decisions
WHERE decision IN ('APPROVED', 'REJECTED');
ALTER VIEW public.v_api_audit_decisions OWNER TO sireader_view_owner;

