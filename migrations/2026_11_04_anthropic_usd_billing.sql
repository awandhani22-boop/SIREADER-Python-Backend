ALTER TABLE ai_usage_logs
    ADD COLUMN IF NOT EXISTS analysis_log_id integer NULL;

-- Backfill defensif: pastikan semua baris lama eksplisit IDR.
UPDATE ai_usage_logs
   SET billing_currency = 'IDR'
 WHERE billing_currency IS NULL;

-- ------------------------------------------------------------
-- 2. CONSTRAINT
-- ------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'ck_ai_usage_logs_billing_currency'
    ) THEN
        ALTER TABLE ai_usage_logs
            ADD CONSTRAINT ck_ai_usage_logs_billing_currency
            CHECK (billing_currency IN ('IDR', 'USD'));
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'ck_ai_usage_logs_non_negative_usd'
    ) THEN
        ALTER TABLE ai_usage_logs
            ADD CONSTRAINT ck_ai_usage_logs_non_negative_usd
            CHECK (cost_usd >= 0 AND reserved_usd >= 0);
    END IF;
END $$;

-- ------------------------------------------------------------
-- 3. INDEX
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS ix_ai_usage_logs_currency_usage_date
    ON ai_usage_logs (billing_currency, usage_date);

CREATE INDEX IF NOT EXISTS ix_ai_usage_logs_analysis_log_id
    ON ai_usage_logs (analysis_log_id);

-- ------------------------------------------------------------
-- 4. TABEL ALERT BUDGET
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_usage_alerts (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_currency  varchar(3)   NOT NULL,
    period_start      date         NOT NULL,
    threshold_percent integer      NOT NULL,
    budget_amount     numeric(18, 6) NOT NULL,
    spent_amount      numeric(18, 6) NOT NULL,
    percent_used      numeric(9, 4)  NOT NULL,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    delivered_at      timestamptz  NULL,
    CONSTRAINT ck_ai_usage_alerts_currency
        CHECK (billing_currency IN ('IDR', 'USD')),
    CONSTRAINT ck_ai_usage_alerts_threshold
        CHECK (threshold_percent > 0 AND threshold_percent <= 100)
);

-- Dedup: satu alert per threshold per siklus budget per mata uang.
CREATE UNIQUE INDEX IF NOT EXISTS uq_ai_usage_alert_period_threshold
    ON ai_usage_alerts (billing_currency, period_start, threshold_percent);

CREATE INDEX IF NOT EXISTS ix_ai_usage_alerts_period_start
    ON ai_usage_alerts (period_start);

-- ------------------------------------------------------------
-- 5. TABEL ANTREAN PESAN BELUM DIANALISIS
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_pending_messages (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dedup_key           varchar(120) NOT NULL,
    chat_id             bigint       NOT NULL,
    telegram_message_id bigint       NOT NULL,
    analysis_log_id     integer      NULL,
    status              varchar(20)  NOT NULL DEFAULT 'PENDING',
    reason              varchar(100) NULL,
    attempts            integer      NOT NULL DEFAULT 0,
    claimed_by          varchar(100) NULL,
    claimed_at          timestamptz  NULL,
    next_attempt_at     timestamptz  NULL,
    last_error          text         NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_ai_pending_status
        CHECK (status IN ('PENDING', 'CLAIMED', 'ANALYZED', 'DISCARDED'))
);

-- Satu pesan sumber hanya boleh antre sekali.
CREATE UNIQUE INDEX IF NOT EXISTS uq_ai_pending_dedup
    ON ai_pending_messages (dedup_key);

CREATE INDEX IF NOT EXISTS ix_ai_pending_status
    ON ai_pending_messages (status);

CREATE INDEX IF NOT EXISTS ix_ai_pending_chat_id
    ON ai_pending_messages (chat_id);

CREATE INDEX IF NOT EXISTS ix_ai_pending_analysis_log_id
    ON ai_pending_messages (analysis_log_id);

