-- SIREADER: PERSISTENT TRADE DECISION WATCHES
-- ============================================================
-- Draft migration PostgreSQL / Supabase.
-- Aditif saja: tidak mengubah tabel lama.
-- Jalankan manual setelah review dan backup database.
--
-- Fungsi:
--   Menyimpan episode yang menunggu spread kembali normal.
--
-- Tidak ada koneksi MT5 atau order execution dalam migration ini.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS trade_decision_watches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    analysis_log_id integer NOT NULL,
    trade_episode_id integer NOT NULL,

    symbol varchar(64) NOT NULL,
    broker_server varchar(128),

    status varchar(32) NOT NULL DEFAULT 'WAITING_FOR_SPREAD',

    spread_pips numeric(18, 5),
    maximum_spread_pips numeric(18, 5) NOT NULL,

    last_bid numeric(18, 5),
    last_ask numeric(18, 5),

    last_checked_at timestamptz,
    next_check_at timestamptz NOT NULL DEFAULT now(),

    check_count integer NOT NULL DEFAULT 0,
    last_reason text,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,

    CONSTRAINT fk_trade_decision_watch_analysis
        FOREIGN KEY (analysis_log_id)
        REFERENCES ai_analysis_logs(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_trade_decision_watch_episode
        FOREIGN KEY (trade_episode_id)
        REFERENCES trade_episodes(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_trade_decision_watch_analysis
        UNIQUE (analysis_log_id),

    CONSTRAINT ck_trade_decision_watch_status
        CHECK (
            status IN (
                'WAITING_FOR_SPREAD',
                'RECHECKING',
                'RESOLVED',
                'SKIPPED',
                'CANCELLED',
                'EXPIRED',
                'ERROR'
            )
        ),

    CONSTRAINT ck_trade_decision_watch_max_spread_positive
        CHECK (maximum_spread_pips > 0),

    CONSTRAINT ck_trade_decision_watch_spread_nonnegative
        CHECK (spread_pips IS NULL OR spread_pips >= 0),

    CONSTRAINT ck_trade_decision_watch_check_count
        CHECK (check_count >= 0)
);

CREATE INDEX IF NOT EXISTS
    ix_trade_decision_watches_status_next_check
ON trade_decision_watches (status, next_check_at);

CREATE INDEX IF NOT EXISTS
    ix_trade_decision_watches_episode_status
ON trade_decision_watches (trade_episode_id, status);

COMMIT;
